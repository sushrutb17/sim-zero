// Regenerates public/ui/{overhead,autopilot,kneeboard}-labels.uikitml from src/xr/cockpit/layout.ts + THEME,
// so printed labels stay aligned with the 3D control positions. Run: node tools/gen-label-panels.mjs
// UIKitML numeric units are centimetres: 1 m of LAYOUT = 100.
import { writeFileSync } from 'node:fs';
import { ZONES, LOCAL } from '../src/xr/cockpit/layout.ts';
import { THEME, fontSizeForCap } from '../src/xr/theme.ts';

const cm = (m) => +(m * 100).toFixed(3);
const FS = {
  small: cm(fontSizeForCap(THEME.text.capM.min)),
  body: cm(fontSizeForCap(THEME.text.capM.body)),
  readout: cm(fontSizeForCap(THEME.text.capM.readout)),
  title: cm(fontSizeForCap(THEME.text.capM.title)),
  symbol: cm(fontSizeForCap(0.02)),
};

function panel(zoneKey, items) {
  const [zw, zh] = ZONES[zoneKey].size;
  const W = cm(zw);
  const H = cm(zh);
  const out = [];
  for (const it of items) {
    const bw = it.w ?? 12;
    const bh = it.h ?? +(it.fs * 1.4).toFixed(2);
    const left = +(W / 2 + cm(it.x) - bw / 2).toFixed(3);
    const top = +(H / 2 - cm(it.y) - bh / 2).toFixed(3);
    out.push(
      `  <div ${it.id ? `id="${it.id}" ` : ''}style="position-type: absolute; position-left: ${left}; position-top: ${top}; width: ${bw}; height: ${bh}; text-align: center; font-size: ${it.fs}; font-weight: ${it.fw ?? 500}; color: ${it.color ?? THEME.color.textDim}; letter-spacing: ${it.ls ?? 0.04};">${it.text}</div>`,
    );
  }
  return `<!-- Generated by tools/gen-label-panels.mjs from src/xr/cockpit/layout.ts. Do not edit by hand. -->\n<div style="width: ${W}; height: ${H}; flex-direction: column;">\n${out.join('\n')}\n</div>\n`;
}

const label = (text, x, y, extra = {}) => ({ text, x, y, fs: FS.small, ...extra });
const readout = (id, x, y) => ({ id, text: '000', x, y, fs: FS.readout, fw: 600, color: THEME.color.text, w: 6, ls: 0 });
const symbol = (text, x, y) => ({ text, x, y, fs: FS.symbol, fw: 600, color: THEME.color.text, w: 4, ls: 0 });

const stepper = (key, title, idr) => {
  const [x, y] = LOCAL[key];
  return [label(title, x, y + 0.035, { w: 14 }), readout(idr, x, y), symbol('-', x - 0.056, y), symbol('+', x + 0.056, y)];
};

const ap = [
  ...stepper('baro.set', 'BARO hPa', 'val-baro-set'),
  ...stepper('ap.hdg', 'HDG', 'val-ap-hdg'),
  ...stepper('ap.alt', 'ALT FT', 'val-ap-alt'),
];
const [lx, ly] = LOCAL['ap.lateral'];
const [ex, ey] = LOCAL['ap.engage'];
const [vx, vy] = LOCAL['ap.vertical'];
ap.push(
  label('LATERAL', lx, ly + 0.035, { w: 12 }),
  label('AUTOPILOT', ex, ey + 0.035, { w: 12 }),
  label('VERTICAL', vx, vy + 0.035, { w: 12 }),
  label('HDG', lx - 0.026, ly, { w: 4, color: THEME.color.text }),
  label('NAV', lx + 0.026, ly, { w: 4, color: THEME.color.text }),
  label('AP', ex, ey - 0.004, { w: 4.5, color: THEME.color.text, fs: FS.body, fw: 600 }),
  label('CLB', vx - 0.026, vy, { w: 4, color: THEME.color.text }),
  label('HOLD', vx + 0.026, vy, { w: 4, color: THEME.color.text }),
);

const toggleLabels = (key, title, idr) => {
  const [x, y] = LOCAL[key];
  return [label(title, x, y + 0.04, { w: 10 }), { id: idr, text: 'OFF', x, y: y - 0.045, fs: FS.small, fw: 600, w: 8, color: THEME.color.textDim }];
};
const ov = [
  label('ELECTRICAL', -0.1, 0.066, { w: 24, fs: FS.small }),
  label('LIGHTS', 0.1425, 0.066, { w: 24, fs: FS.small }),
  ...toggleLabels('elec.gen1', 'GEN 1', 'val-elec-gen1'),
  ...toggleLabels('elec.gen2', 'GEN 2', 'val-elec-gen2'),
  ...toggleLabels('elec.busTie', 'BUS TIE', 'val-elec-busTie'),
  ...toggleLabels('lights.landing', 'LAND', 'val-lights-landing'),
  ...toggleLabels('lights.strobe', 'STROBE', 'val-lights-strobe'),
];
const [px, py] = LOCAL['practice.toggle'];
const kb = [
  label('KNEEBOARD', 0, ZONES.kneeboard.size[1] / 2 - 0.02, { w: 16, fs: FS.body, color: THEME.color.text }),
  label('PRACTICE MODE', px, py + 0.042, { w: 16 }),
  { id: 'val-practice-toggle', text: 'OFF', x: px + 0.04, y: py, fs: FS.small, fw: 600, w: 8, color: THEME.color.textDim },
];

writeFileSync(new URL('../public/ui/autopilot-labels.uikitml', import.meta.url), panel('autopilot', ap));
writeFileSync(new URL('../public/ui/overhead-labels.uikitml', import.meta.url), panel('overhead', ov));
writeFileSync(new URL('../public/ui/kneeboard-labels.uikitml', import.meta.url), panel('kneeboard', kb));
console.log('label panels written');
